async function seedIcons() {
    console.log(`Starting icon seeding to R2 bucket '${R2_BUCKET}/${BUCKET_FOLDER}'...`);

    // No need to create bucket - assumed to exist in R2 (lms-assets)

    // Upload Icons
    for (const [category, categoryIcons] of Object.entries(icons)) {
        console.log(`Processing category: ${category}`);

        for (const [filename, svgContent] of Object.entries(categoryIcons)) {
            // Keep the 'icons' folder prefix in R2
            const r2Key = `${BUCKET_FOLDER}/${category}/${filename}`;
            console.log(`  Uploading ${r2Key}...`);

            const command = new PutObjectCommand({
                Bucket: R2_BUCKET,
                Key: r2Key,
                Body: svgContent,
                ContentType: 'image/svg+xml'
            });

            try {
                await r2Client.send(command);
                console.log(`  Success: ${r2Key}`);
            } catch (error) {
                console.error(`  Failed to upload ${r2Key}:`, error.message);
            }
        }
    }

    console.log('Icon seeding completed.');
}

seedIcons().catch(console.error);
